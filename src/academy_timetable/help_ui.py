class HelpDialog(QDialog):
    def __init__(self, parent):
        super().__init__(parent)
        self.setWindowTitle("프로그램 사용 방법")
        self.resize(720, 560)
        layout = QVBoxLayout(self)

        toolbar = QHBoxLayout()
        label = QLabel("목차")
        self.topic = QComboBox()
        self.topic.setAccessibleName("사용 방법 목차")
        self.topic.addItems([title for title, _ in TOPICS])
        label.setBuddy(self.topic)
        toolbar.addWidget(label)
        toolbar.addWidget(self.topic, 1)
        close = QPushButton("닫기")
        close.clicked.connect(self.close)
        toolbar.addWidget(close)
        layout.addLayout(toolbar)

        self.reader = QTextBrowser()
        self.reader.setAccessibleName("사용 방법 본문")
        self.reader.setStyleSheet("QTextBrowser { background: white; color: #20324b; font-size: 15px; }")
        self.reader.document().setDocumentMargin(18)
        layout.addWidget(self.reader, 1)
        self.topic.currentIndexChanged.connect(self.show_topic)
        self.show_topic(0)

    def show_topic(self, index):
        title, content = TOPICS[index]
        self.reader.setMarkdown(f"## {title}\n\n{content.strip()}")
        self.reader.verticalScrollBar().setValue(0)
